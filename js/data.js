function toothInfo(num) {
  const q = Math.floor(num / 10), p = num % 10;
  const primary = q >= 5;
  const jaw = [1, 2, 5, 6].includes(q) ? 'upper' : 'lower';
  const base = (primary ? PRIMARY : PERMANENT)[jaw][p];
  if (!base) return null;
  return { num, q, p, primary, jaw, quadrant: QUADRANTS[q], ...base };
}

